#!/usr/bin/env python3
"""The Play Store icon (512 x 512) from the launcher icon's own resources.

Reads the adaptive icon's background colour (owl_night) and the owl vector (ic_owl.xml) with the
inset its launcher foreground gives it, and writes icon.svg as the launcher shows it: the central
72dp of the 108dp layers, so the owl sits in the square as large as on the home screen. Play adds
its own rounded mask, so the square is full bleed. Then renders icon-512.png with rsvg-convert
(librsvg) and makes it the 32-bit PNG Play asks for with ImageMagick.

    python3 -I docs/play/make_icon.py
"""
import os
import subprocess
import sys
import xml.etree.ElementTree as ET

A = "{http://schemas.android.com/apk/res/android}"
HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "..", "app", "src", "main", "res")

LAYER_DP = 108.0  # an adaptive icon's layers
SHOWN_DP = 72.0  # what the launcher's mask shows of them
SIZE_PX = 512


def color(value):
    """#AARRGGBB or #RRGGBB as (#rrggbb, opacity)."""
    v = value.lstrip("#")
    if len(v) == 8:
        return "#" + v[2:].lower(), int(v[:2], 16) / 255
    return "#" + v[-6:].lower(), 1.0


def background():
    colors = ET.parse(os.path.join(RES, "values", "colors.xml")).getroot()
    adaptive = ET.parse(os.path.join(RES, "mipmap-anydpi", "ic_launcher.xml")).getroot()
    ref = adaptive.find("background").get(A + "drawable")
    name = ref.split("/")[-1]
    return next(c.text for c in colors if c.get("name") == name)


def inset_fraction():
    fg = ET.parse(os.path.join(RES, "drawable", "ic_launcher_foreground.xml")).getroot()
    assert fg.tag == "inset" and fg.get(A + "drawable") == "@drawable/ic_owl", "foreground is no longer the inset owl"
    return float(fg.get(A + "inset").rstrip("%")) / 100


def svg_paths(node, out, indent="    "):
    for child in node:
        if child.tag == "group":
            tx, ty = child.get(A + "translateX", "0"), child.get(A + "translateY", "0")
            out.append(f'{indent}<g transform="translate({tx} {ty})">')
            svg_paths(child, out, indent + "  ")
            out.append(f"{indent}</g>")
        elif child.tag == "path":
            attrs = [f'd="{child.get(A + "pathData")}"']
            fill = child.get(A + "fillColor")
            if fill:
                rgb, alpha = color(fill)
                attrs.append(f'fill="{rgb}"')
                if alpha < 1:
                    attrs.append(f'fill-opacity="{alpha:.3f}"')
            else:
                attrs.append('fill="none"')
            if child.get(A + "fillType") == "evenOdd":
                attrs.append('fill-rule="evenodd"')
            stroke = child.get(A + "strokeColor")
            if stroke:
                rgb, alpha = color(stroke)
                attrs.append(f'stroke="{rgb}" stroke-width="{child.get(A + "strokeWidth", "1")}"')
                if alpha < 1:
                    attrs.append(f'stroke-opacity="{alpha:.3f}"')
                join = child.get(A + "strokeLineJoin")
                if join:
                    attrs.append(f'stroke-linejoin="{join}"')
                cap = child.get(A + "strokeLineCap")
                if cap:
                    attrs.append(f'stroke-linecap="{cap}"')
            out.append(f"{indent}<path {' '.join(attrs)}/>")
        else:
            sys.exit(f"ic_owl.xml: {child.tag} isn't handled here")


def main():
    owl = ET.parse(os.path.join(RES, "drawable", "ic_owl.xml")).getroot()
    viewport = float(owl.get(A + "viewportWidth"))
    assert viewport == float(owl.get(A + "viewportHeight")), "the owl's viewport is no longer square"
    px_per_dp = SIZE_PX / SHOWN_DP
    owl_dp = LAYER_DP * (1 - 2 * inset_fraction())
    offset = (LAYER_DP * inset_fraction() - (LAYER_DP - SHOWN_DP) / 2) * px_per_dp
    scale = owl_dp * px_per_dp / viewport
    bg, _ = color(background())

    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{SIZE_PX}" height="{SIZE_PX}" viewBox="0 0 {SIZE_PX} {SIZE_PX}">',
        "  <!-- Generated by make_icon.py from app/src/main/res: edit the resources, not this. -->",
        f'  <rect width="{SIZE_PX}" height="{SIZE_PX}" fill="{bg}"/>',
        f'  <g transform="translate({offset:.3f} {offset:.3f}) scale({scale:.6f})">',
    ]
    svg_paths(owl, out)
    out += ["  </g>", "</svg>", ""]
    svg = os.path.join(HERE, "icon.svg")
    with open(svg, "w") as f:
        f.write("\n".join(out))
    png = os.path.join(HERE, "icon-512.png")
    subprocess.run(["rsvg-convert", "-w", str(SIZE_PX), "-h", str(SIZE_PX), "-o", png, svg], check=True)
    # Play asks for a 32-bit PNG; rsvg-convert writes an opaque one as 24-bit RGB.
    subprocess.run(["magick", png, f"PNG32:{png}"], check=True)
    print(f"{os.path.relpath(svg)} and {os.path.relpath(png)}: owl {owl_dp:.1f}dp of {SHOWN_DP:.0f}dp shown, on {bg}")


if __name__ == "__main__":
    main()
